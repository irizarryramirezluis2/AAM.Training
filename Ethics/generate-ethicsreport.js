/**
 * Ethics Compliance Report Generator
 * Generates an automated audit log report for tracking compliance history.
 */

const fs = require('fs');
const path = require('path');

const REPORT_FILE = path.join(__dirname, '../ETHICS_COMPLIANCE_REPORT.md');
const INPUT_FILE = process.argv[2] || 'ethics-report.json';

function generateReport() {
  console.log('Generating Ethics Compliance Report...');

  let violations = [];
  if (fs.existsSync(INPUT_FILE)) {
    try {
      const rawData = fs.readFileSync(INPUT_FILE, 'utf8');
      const parsedData = JSON.parse(rawData);
      violations = parsedData.violations || parsedData.issues || [];
    } catch (e) {
      console.warn(`Warning: Could not parse ${INPUT_FILE}. Proceeding with default state.`);
    }
  }

  const timestamp = new Date().toISOString();
  const isPassed = violations.length === 0;

  let reportContent = `# Ethics & Security Compliance Report

**Generated Date:** ${timestamp}
**Compliance Status:** ${isPassed ? 'PASSED' : 'FAILED'}
**Audit Level:** Level 4 (Enforced)

## Verification Summary
`;

  if (isPassed) {
    reportContent += `- **Hardcoded Secrets Check:** PASSED
- **Audit Logging Integration:** PASSED
- **L4 Multi-Factor Auth Enforcement:** PASSED
- **Privacy Policy Data Handling:** PASSED
`;
  } else {
    reportContent += `❌ **Violations Detected (${violations.length}):**\n\n`;
    violations.forEach((v, index) => {
      reportContent += `${index + 1}. **${v.severity || 'HIGH'}**: ${v.message || v}\n`;
    });
  }

  reportContent += `\n---\n*This report was automatically generated by the pre-commit ethics pipeline.*\n`;

  try {
    fs.writeFileSync(REPORT_FILE, reportContent, 'utf8');
    console.log(`✅ Compliance report successfully updated: ${REPORT_FILE}`);
    
    if (!isPassed) {
      console.error(`❌ Ethics check failed with ${violations.length} violations.`);
      process.exit(1);
    }
    
    process.exit(0);
  } catch (err) {
    console.error(`❌ Failed to write compliance report: ${err.message}`);
    process.exit(1);
  }
}

generateReport();